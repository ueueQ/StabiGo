#ifndef _DRV_I2C_SW_H
#define _DRV_I2C_SW_H

#include "BaseTypes.h"


/*******************************************************************************
* 宏定义 *
*******************************************************************************/
#define I2C_ACK   ((Uint8)0u)   
#define I2C_NACK  ((Uint8)1u)   


/*******************************************************************************
* 结束宏定义 *
*******************************************************************************/

/*******************************************************************************
* 全局数据类型 *
*******************************************************************************/
typedef struct I2c
{
    Uint8 ucDelayUs;   // iic速率调整 
    
    // 需要用户自己注册
    void (*DelayUs)(Uint16 uiUs); 
    void (*SclOut)(Uint8 ucValue);
    void (*SdaOut)(Uint8 ucValue);
    Uint8 (*SdaRead)(void);

    // 无需用户注册

    void (*Start)(struct I2c *ptI2c);
    void (*Stop)(struct I2c *ptI2c);
    void (*Ack)(struct I2c *ptI2c);
    void (*AckNo)(struct I2c *ptI2c);
    Uint8 (*WaitAck)(struct I2c *ptI2c);
    void (*SendByte)(struct I2c *ptI2c, Uint8 ucValue);
    Uint8 (*ReadByte)(struct I2c *ptI2c, Uint8 ucIsAck);
	
} T_I2c;

/*******************************************************************************
* 结束全局数据类型 *
*******************************************************************************/

/*******************************************************************************
* 全局函数原型 *
*******************************************************************************/
void I2cInit(T_I2c *ptI2c);

/*******************************************************************************
* 结束全局函数原型 *
*******************************************************************************/

#endif


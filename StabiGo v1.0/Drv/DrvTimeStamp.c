#include "DrvTimeStamp.h"

/*******************************************************************************
* 全局变量 *
*******************************************************************************/
static T_TimeStamp gtTsp = {0u};

/*******************************************************************************
* 结束全局变量 *
*******************************************************************************/


/*******************************************************************************
* 函数名称： DrvRemoteTspSet()
* 功能描述： 设置远程时间戳数值
* 输入参数： ullVaule 实际时间戳
* 输出参数： 无
* 返 回 值： 无
* 其它说明：无
*******************************************************************************/
void DrvRemoteTspSet(Uint64 ullVaule)
{
	gtTsp.ullRemoteTimeStamp = ullVaule;
}

/*******************************************************************************
* 函数名称： DrvTspGet()
* 功能描述： 获取时间戳
* 输入参数： 无
* 输出参数： 无
* 返 回 值： 无
* 其它说明： 无
*******************************************************************************/
Uint64 DrvTspGet(void)
{
	return gtTsp.ullRemoteTimeStamp;
}

/*******************************************************************************
* 函数名称： DrvTspAdd()
* 功能描述： 时间戳累加
* 输入参数： 无
* 输出参数： 无
* 返 回 值： 无
* 其它说明： 该函数应该注册到ms累计的计时器中
*******************************************************************************/
void DrvTspAdd(void)
{
	gtTsp.ullRemoteTimeStamp++;
}
